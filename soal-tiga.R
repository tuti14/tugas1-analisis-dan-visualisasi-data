# Rumus Koefisien Keragaman (KV) = (SD / Rata-rata) * 100%

# Matematika
rata_mat <- 75
rata_mat

sd_mat <- 10
sd_mat

kv_mat <- (sd_mat / rata_mat) * 100
kv_mat

# Bahasa Inggris
rata_ing <- 70
rata_ing

sd_ing <- 8
sd_ing

kv_ing <- (sd_ing / rata_ing) * 100
kv_ing

cat("Koefisien Keragaman Matematika:", round(kv_mat, 2), "%\n")
cat("Koefisien Keragaman Bahasa Inggris:", round(kv_ing, 2), "%\n")

